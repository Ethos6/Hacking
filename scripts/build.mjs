#!/usr/bin/env node
// Generates the resource tables in README.md and the JSON used by the website.
//   node scripts/build.mjs          write README.md and site/api/*.json
//   node scripts/build.mjs --check  fail if README.md is out of date (CI)
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT, STATUS, allResources, healthStatus, loadCategories, loadHealth, slug } from './lib.mjs';

const START = '<!-- resources:start (generated by scripts/build.mjs from data/*.json, do not edit by hand) -->';
const END = '<!-- resources:end -->';
const check = process.argv.includes('--check');

const categories = loadCategories();
const health = loadHealth();
const resources = allResources(categories);
const tracked = resources.filter((r) => r.repo && health.repos[r.repo]);
const counts = Object.fromEntries(Object.keys(STATUS).map((s) => [s, 0]));
for (const r of tracked) counts[healthStatus(health.repos[r.repo])]++;

const md = (s) => String(s).replace(/([\\`*_[\]<>|])/g, '\\$1');
const compact = (n) => (n >= 1000 ? `${(n / 1000).toFixed(n >= 10000 ? 0 : 1).replace(/\.0$/, '')}k` : String(n));
const month = (d) => new Date(`${d}T00:00:00Z`).toLocaleDateString('en-US', { month: 'short', year: 'numeric', timeZone: 'UTC' });
const TYPE = { course: 'Course', platform: 'Platform', lab: 'Lab', tool: 'Tool', reference: 'Reference', list: 'List' };
const LEVEL = { beginner: 'Beginner', intermediate: 'Intermediate', advanced: 'Advanced' };

function healthCell(r) {
  if (!r.repo) return r.free ? 'Free' : '—';
  const h = health.repos[r.repo];
  const s = healthStatus(h);
  if (!h || !s) return '—';
  return `${STATUS[s].icon} ★ ${compact(h.stars)}<br><sub>${month(h.last_commit)}</sub>`;
}

function row(r) {
  const extras = [];
  if (r.note) extras.push(`<br><sub>${md(r.note)}</sub>`);
  const meta = [TYPE[r.type], r.level ? LEVEL[r.level] : 'All levels'].join(' · ');
  return `| [**${md(r.name)}**](${r.url})<br><sub>${meta}</sub> | ${md(r.description)}${extras.join('')} | ${healthCell(r)} |`;
}

const toc = categories.map((c) => `[${c.category}](#${slug(c.category)})`).join(' · ');
const sections = categories.map((c) =>
  [
    `### ${c.category}`,
    '',
    `${c.description}`,
    '',
    '| Resource | What it is | Health |',
    '| :-- | :-- | :-- |',
    ...c.resources.map((r) => row({ ...r, category: c.id })),
    '',
    '<div align="right"><a href="#contents">↑ back to contents</a></div>',
  ].join('\n'),
);

const legend = Object.values(STATUS)
  .map((s) => `${s.icon} ${s.label} (${s.hint})`)
  .join(' · ');

const generated = [
  START,
  '',
  `<p align="center"><b>${resources.length} resources</b> in <b>${categories.length} categories</b> · <b>${tracked.length}</b> GitHub projects health-checked weekly (last check: ${health.updated ?? 'pending'})<br>`,
  `${counts.active} active · ${counts.maintained} maintained · ${counts.slow} slow · ${counts.stale} stale · ${counts.archived} archived</p>`,
  '',
  `**Jump to:** ${toc}`,
  '',
  `<sub>**Health:** ${legend}. Stars and dates come from the GitHub API.</sub>`,
  '',
  sections.join('\n\n'),
  '',
  END,
].join('\n');

const readmePath = join(ROOT, 'README.md');
const readme = readFileSync(readmePath, 'utf8');
const a = readme.indexOf(START);
const b = readme.indexOf(END);
if (a < 0 || b < 0) {
  console.error('README.md is missing the resources:start / resources:end markers.');
  process.exit(1);
}
const nextReadme = readme.slice(0, a) + generated + readme.slice(b + END.length);

if (check) {
  if (nextReadme !== readme) {
    console.error('✖ README.md is out of date. Run `npm run build` and commit the result.');
    process.exit(1);
  }
  console.log('✔ README.md is up to date');
  process.exit(0);
}
writeFileSync(readmePath, nextReadme);

const api = join(ROOT, 'site', 'api');
mkdirSync(api, { recursive: true });
const out = resources.map((r) => {
  const h = r.repo ? health.repos[r.repo] : undefined;
  return { ...r, ...(h ? { stars: h.stars, last_commit: h.last_commit, status: healthStatus(h) } : {}) };
});
writeFileSync(join(api, 'resources.json'), `${JSON.stringify({ generated: new Date().toISOString().slice(0, 10), health_checked: health.updated, count: out.length, resources: out }, null, 2)}\n`);
writeFileSync(join(api, 'categories.json'), `${JSON.stringify(categories.map((c) => ({ id: c.id, title: c.category, description: c.description, count: c.resources.length })), null, 2)}\n`);
console.log(`✔ Built README.md and site/api for ${resources.length} resources`);
